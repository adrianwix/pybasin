"""
Ground-truth fixtures for `PairwiseComparisonClusterer`'s algorithmic edge cases --
behavior that isn't naturally exercised by either full case-study pipeline
(`tests/accuracy/henon_map`, `tests/accuracy/magnetic_pendulum`), generated by
running the real `Attractors.jl` (@ `df7c420b4c1d69e1d662bb679a46f8ef8b53bcaa`)
`GroupViaPairwiseComparison` grouping algorithm end to end.

Fixtures:
  - dumb_map: analytic 2D map, `GroupViaPairwiseComparison()` defaults
  - aggregation_threshold: same dumb map features, `rescale_features=false`,
    `threshold=3.0` (single merged group) vs `threshold=0.5` (matches the unmerged split)
  - order_permutation: dumb_map's own features grouped in original vs. permuted order
  - toy_chain_order: a minimal 3-point order-dependence example ([0.0, 0.9, 1.8], threshold=1.0)

Run with:
    julia --project=packages/pybasin/tests/accuracy/_julia_project \
        packages/pybasin/tests/accuracy/pairwise/generate_algorithmic_fixtures.jl
"""

using DynamicalSystems: DeterministicIteratedMap, AttractorsViaFeaturizing,
    GroupViaPairwiseComparison, group_features, extract_features, ics_from_grid
using StaticArrays: SVector
using Random: seed!, randperm
using JSON

const OUTPUT_PATH = joinpath(@__DIR__, "fixtures", "pairwise_algorithmic_fixtures.json")

# --- helpers -------------------------------------------------------------------------

"""Fraction of each label in `labels`, keyed by the (1-based) label as a string (JSON
object keys must be strings; the Python side re-keys them back to ints)."""
function label_fractions(labels)
    n = length(labels)
    fracs = Dict{String, Float64}()
    for l in unique(labels)
        fracs[string(l)] = count(==(l), labels) / n
    end
    return fracs
end

as_json_point(v) = Float64.(collect(v))
as_json_matrix(A) = [as_json_point(p) for p in A]

# --- Fixture: dumb map + aggregation threshold + order permutation --------------------
# `dumb_map`, the 3x3 grid, `featurizer(A,t)=A[end]`, and `GroupViaPairwiseComparison()`
# defaults are verbatim from `Attractors.jl` @ `df7c420b4c1d69e1d662bb679a46f8ef8b53bcaa`
# `test/nonlocal/stability_measures_accumulator.jl` `@testset "accummulator with
# featurizer"` (lines 332-361), whose own assertion
# (`sort!(collect(values(fs))) .≈ [0.333..., 0.666...]`) is exactly the `dumb_map` fixture's
# expected fractions below. "aggregation_threshold" regroups those same features at
# `threshold=3.0`/`threshold=0.5`, matching that same file's `@testset "aggregation"`
# (lines 373-421), which merges two already-identified attractors at x=+1/x=-1 the same way.
# Line numbers and content are only guaranteed to match at that commit -- re-verify
# against current Attractors.jl source before trusting them at a later one.
function dumb_map(z, p, n)
    x, y = z
    r = p[1]
    if r < 0.5
        return SVector(0.0, 0.0)
    else
        return x ≥ 0 ? SVector(r, r) : SVector(-r, -r)
    end
end

function run_dumb_map_fixtures()
    dynamics = DeterministicIteratedMap(dumb_map, [1.0, 1.0], [1.0])
    featurizer(A, t) = A[end]
    grid = ([-1, 0, 1], [-1, 0, 1])
    ics = ics_from_grid(grid)

    default_config = GroupViaPairwiseComparison()
    mapper = AttractorsViaFeaturizing(dynamics, featurizer, default_config)
    features = extract_features(mapper, ics; show_progress = false)
    labels = group_features(features, default_config)

    merge_config = GroupViaPairwiseComparison(threshold = 3.0, rescale_features = false)
    labels_merge = group_features(features, merge_config)

    separate_config = GroupViaPairwiseComparison(threshold = 0.5, rescale_features = false)
    labels_separate = group_features(features, separate_config)

    dumb_map_fixture = Dict(
        "ics" => as_json_matrix(ics),
        "features" => as_json_matrix(features),
        "threshold" => default_config.threshold,
        "rescale_features" => default_config.rescale_features,
        "labels_1based" => labels,
        "fractions" => label_fractions(labels),
    )
    aggregation_fixture = Dict(
        "features" => as_json_matrix(features),
        "threshold_merge" => merge_config.threshold,
        "labels_merge_1based" => labels_merge,
        "fractions_merge" => label_fractions(labels_merge),
        "threshold_separate" => separate_config.threshold,
        "labels_separate_1based" => labels_separate,
        "fractions_separate" => label_fractions(labels_separate),
    )

    seed!(42)
    perm = randperm(length(features))
    features_permuted = features[perm]
    labels_permuted = group_features(features_permuted, default_config)
    order_permutation_fixture = Dict(
        "features" => as_json_matrix(features),
        "threshold" => default_config.threshold,
        "rescale_features" => default_config.rescale_features,
        "permutation_1based" => perm,
        "labels_original_1based" => labels,
        "labels_permuted_1based" => labels_permuted,
    )

    return dumb_map_fixture, aggregation_fixture, order_permutation_fixture
end

# --- Fixture: minimal toy order-dependence example ------------------------------------
function run_toy_chain_order_fixture()
    values = [SVector(0.0), SVector(0.9), SVector(1.8)]
    config = GroupViaPairwiseComparison(threshold = 1.0, rescale_features = false)
    labels_original = group_features(values, config)

    perm = [3, 2, 1]
    labels_permuted = group_features(values[perm], config)

    return Dict(
        "values" => as_json_matrix(values),
        "threshold" => config.threshold,
        "labels_original_1based" => labels_original,
        "permutation_1based" => perm,
        "labels_permuted_1based" => labels_permuted,
    )
end

# --- main ------------------------------------------------------------------------------
function main()
    println("Running dumb map + aggregation threshold + order permutation fixtures...")
    dumb_map_fixture, aggregation_fixture, order_permutation_fixture = run_dumb_map_fixtures()

    println("Running toy chain order-permutation fixture...")
    toy_chain_fixture = run_toy_chain_order_fixture()

    output = Dict(
        "dumb_map" => dumb_map_fixture,
        "aggregation_threshold" => aggregation_fixture,
        "order_permutation" => order_permutation_fixture,
        "toy_chain_order" => toy_chain_fixture,
    )

    mkpath(dirname(OUTPUT_PATH))
    open(OUTPUT_PATH, "w") do f
        JSON.print(f, output, 2)
    end
    println("Saved fixtures to: $OUTPUT_PATH")

    println("\ndumb_map fractions: ", dumb_map_fixture["fractions"])
    println("aggregation (merge) fractions: ", aggregation_fixture["fractions_merge"])
    println("aggregation (separate) fractions: ", aggregation_fixture["fractions_separate"])
end

main()
