from __future__ import annotations

import argparse
import os
import re
import shlex
import subprocess
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class TimingRow:
    source: str
    group: str
    path: str
    shape: tuple[int, int, int]
    median_ms: float


def shell_join(command: list[str]) -> str:
    return " ".join(shlex.quote(part) for part in command)


def parse_shape(raw: str) -> tuple[int, int, int]:
    values = [int(part.strip()) for part in raw.strip("`() ").split(",") if part.strip()]
    if len(values) != 3:
        raise ValueError(f"Expected a 3D shape, got {raw!r}")
    return values[0], values[1], values[2]


def parse_table_rows(report: str, *, source: str) -> list[TimingRow]:
    rows: list[TimingRow] = []
    for line in report.splitlines():
        if not line.startswith("| ") or line.startswith("| Group ") or line.startswith("|---"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        group, path, shape, median_ms = cells[:4]
        try:
            rows.append(
                TimingRow(
                    source=source,
                    group=group,
                    path=path,
                    shape=parse_shape(shape),
                    median_ms=float(median_ms),
                )
            )
        except ValueError:
            continue
    return rows


def artifact_lines(report: str) -> list[str]:
    lines: list[str] = []
    in_artifacts = False
    for line in report.splitlines():
        if line == "## Artifacts" or line == "## Packages":
            in_artifacts = True
            continue
        if in_artifacts and line.startswith("## "):
            break
        if in_artifacts and line.startswith("- "):
            lines.append(line)
    return lines


def dependency_block(report: str) -> str | None:
    match = re.search(r"## Runtime Dependencies\n\n```text\n(.*?)\n```", report, re.DOTALL)
    return match.group(1).strip() if match else None


def table_for(rows: list[TimingRow]) -> str:
    lines = [
        "| Source | Method | Median ms |",
        "|---|---|---:|",
    ]
    for row in sorted(rows, key=lambda item: item.median_ms):
        lines.append(f"| {row.source} | {row.path} | {row.median_ms:.6g} |")
    return "\n".join(lines)


def write_consolidated_report(
    path: Path,
    *,
    rows: list[TimingRow],
    aoti_report: str,
    standalone_report: str,
    executorch_report: str,
    commands: list[list[str]],
) -> None:
    shapes = sorted({row.shape for row in rows}, key=lambda shape: (shape[0], shape[1], shape[2]))
    lines = [
        "# Basic Statistics Export Backend Report",
        "",
        "This report is generated by `packages/tstorch/experiments/exporting/run_basic_stats_report.py`.",
        "",
        "It compares the same `mean`, `maximum`, `minimum` feature plan across PyTorch/AOTI and",
        "standalone generated C/C++ paths. Timing tables are grouped by batch size so methods can",
        "be compared directly for the same input shape.",
        "",
        "## How to Read Labels",
        "",
        "- `AOTI` rows use PyTorch `torch.export` + AOTInductor artifacts and require a LibTorch",
        "  runtime at execution time.",
        "- `Standalone C` rows use the generated C kernel from `standalone_codegen_basic_stats` and",
        "  do not depend on PyTorch or LibTorch.",
        "- `ExecuTorch` rows use PyTorch `torch.export` + ExecuTorch `.pte` artifacts. The artifact",
        "  is small, but the pip-wheel runtime used here still links against LibTorch.",
        "- `Combined` means `mean`, `maximum`, and `minimum` are computed together for each",
        "  `(batch, state)` series.",
        "- `Separated` means one feature is computed per benchmark row.",
        "- `TorchFeatureExtractor generated kernel, AOTI C++` is the exported internal kernel built",
        "  from the configured `TorchFeatureExtractor` plan.",
        "- `basic_stats_f32` is the standalone generated C function with a plain C ABI.",
        "",
    ]

    for shape in shapes:
        shape_rows = [row for row in rows if row.shape == shape]
        combined = [
            row
            for row in shape_rows
            if row.group in {"combined", "standalone_codegen", "executorch_cpp"}
        ]
        separated = [row for row in shape_rows if row.group == "separated"]
        lines.extend([f"## Batch {shape[0]}", "", f"Shape: `{shape}`", ""])
        if combined:
            lines.extend(["### Combined", "", table_for(combined), ""])
        if separated:
            lines.extend(["### Separated", "", table_for(separated), ""])

    lines.extend(["## Artifacts", "", "### AOTI", ""])
    lines.extend(artifact_lines(aoti_report) or ["- No artifact lines found."])
    lines.extend(["", "### Standalone Codegen", ""])
    lines.extend(artifact_lines(standalone_report) or ["- No artifact lines found."])
    lines.extend(["", "### ExecuTorch", ""])
    lines.extend(artifact_lines(executorch_report) or ["- No artifact lines found."])

    deps = dependency_block(standalone_report)
    if deps:
        lines.extend([
            "",
            "## Standalone Runtime Dependencies",
            "",
            "```text",
            deps,
            "```",
        ])
    executorch_deps = dependency_block(executorch_report)
    if executorch_deps:
        lines.extend([
            "",
            "## ExecuTorch Runtime Dependencies",
            "",
            "```text",
            executorch_deps,
            "```",
        ])

    lines.extend(["", "## Commands", ""])
    for command in commands:
        lines.extend(["```bash", shell_join(command), "```", ""])
    path.write_text("\n".join(lines).rstrip() + "\n")


def parse_args() -> argparse.Namespace:
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser()
    parser.add_argument("--large-batch", type=int, default=10000)
    parser.add_argument("--states", type=int, default=2)
    parser.add_argument("--timesteps", type=int, default=1000)
    parser.add_argument("--python-rounds", type=int, default=10)
    parser.add_argument("--cxx-rounds", type=int, default=20)
    parser.add_argument("--warmup-rounds", type=int, default=2)
    parser.add_argument("--standalone-warmup-rounds", type=int, default=10)
    parser.add_argument("--threads", type=int, default=24)
    parser.add_argument("--output", type=Path, default=root / "basic_stats_report.md")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    root = Path(__file__).resolve().parent
    args.output.parent.mkdir(parents=True, exist_ok=True)
    env = None
    pythonpath = str(root.parents[1] / "src")
    if pythonpath:
        env = {**os.environ, "PYTHONPATH": pythonpath}

    aoti_cmd = [
        "uv",
        "run",
        "python",
        str(root / "aoti_basic_stats" / "run_aoti_basic_stats.py"),
        "--rounds",
        str(args.python_rounds),
        "--warmup-rounds",
        str(args.warmup_rounds),
        "--cxx-rounds",
        str(args.cxx_rounds),
        "--large-batch",
        str(args.large_batch),
        "--states",
        str(args.states),
        "--timesteps",
        str(args.timesteps),
        "--threads",
        "1",
        "--cxx-threads",
        str(args.threads),
    ]
    standalone_cmd = [
        "uv",
        "run",
        "python",
        str(root / "standalone_codegen_basic_stats" / "run_standalone_codegen.py"),
        "--large-batch",
        str(args.large_batch),
        "--states",
        str(args.states),
        "--timesteps",
        str(args.timesteps),
        "--rounds",
        str(args.cxx_rounds),
        "--warmup-rounds",
        str(args.standalone_warmup_rounds),
        "--threads",
        str(args.threads),
    ]
    executorch_cmd = [
        "uv",
        "run",
        "python",
        str(root / "executorch_basic_stats" / "run_executorch_basic_stats.py"),
        "--large-batch",
        str(args.large_batch),
        "--states",
        str(args.states),
        "--timesteps",
        str(args.timesteps),
        "--rounds",
        str(args.cxx_rounds),
        "--warmup-rounds",
        str(args.standalone_warmup_rounds),
        "--threads",
        str(args.threads),
    ]
    display_commands = [
        ["PYTHONPATH=packages/tstorch/src", *aoti_cmd],
        ["PYTHONPATH=packages/tstorch/src", *standalone_cmd],
        ["PYTHONPATH=packages/tstorch/src", *executorch_cmd],
    ]

    subprocess.run(aoti_cmd, check=True, env=env)
    subprocess.run(standalone_cmd, check=True, env=env)
    subprocess.run(executorch_cmd, check=True, env=env)

    aoti_report_path = root / "aoti_basic_stats" / "artifacts" / "report.md"
    standalone_report_path = root / "standalone_codegen_basic_stats" / "artifacts" / "report.md"
    executorch_report_path = root / "executorch_basic_stats" / "artifacts" / "report.md"
    aoti_report = aoti_report_path.read_text()
    standalone_report = standalone_report_path.read_text()
    executorch_report = executorch_report_path.read_text()
    rows = [
        *parse_table_rows(aoti_report, source="AOTI"),
        *parse_table_rows(standalone_report, source="Standalone C"),
        *parse_table_rows(executorch_report, source="ExecuTorch"),
    ]
    write_consolidated_report(
        args.output,
        rows=rows,
        aoti_report=aoti_report,
        standalone_report=standalone_report,
        executorch_report=executorch_report,
        commands=display_commands,
    )
    print(f"report: {args.output}")


if __name__ == "__main__":
    main()
